package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"k8s.io/apimachinery/pkg/util/yaml"
)

const (
	autoGenerationComment = "# This file is auto-generated by KO's hack/generators/conversion-webhook/main.go generator.\n"
	chartCRDsTemplatesDir = "charts/kong-operator/charts/ko-crds/templates"
	chartCRDsFilePath     = "charts/kong-operator/charts/ko-crds/templates/ko-crds.yaml"
	chartCRDsSplitGlob    = "ko-crds-*.yaml"
)

type customResourceDefinitionManifest struct {
	Kind     string `json:"kind"`
	Metadata struct {
		Name string `json:"name"`
	} `json:"metadata"`
	Spec struct {
		Names struct {
			Kind string `json:"kind"`
		} `json:"names"`
	} `json:"spec"`
}

type chartCRDFile struct {
	filePath string
	content  string
}

// Builds CRDs via kustomize and splits them into one Helm chart template file per CRD.
func main() {
	kustomizeBinPath := os.Getenv("KUSTOMIZE_BIN")
	if kustomizeBinPath == "" {
		fmt.Println("KUSTOMIZE_BIN environment variable is not set")
		os.Exit(1)
	}
	fmt.Println("KUSTOMIZE_BIN is set to:", kustomizeBinPath)

	cmd := exec.Command(kustomizeBinPath, "build", "config/crd")
	var out bytes.Buffer
	cmd.Stdout = &out
	if err := cmd.Run(); err != nil {
		fmt.Printf("Failed to execute %s: %v\n", cmd.String(), err)
		os.Exit(1)
	}
	crdContent := out.String()

	splitChartCRDFiles, err := splitChartCRDs(crdContent, chartCRDsTemplatesDir)
	if err != nil {
		fmt.Printf("Failed to split chart CRDs: %v\n", err)
		os.Exit(1)
	}

	if err := removeGeneratedSplitChartCRDFiles(chartCRDsTemplatesDir); err != nil {
		fmt.Printf("Failed to clean old split CRD files: %v\n", err)
		os.Exit(1)
	}

	// The monolithic ko-crds.yaml is no longer generated (it used to hold CRDs
	// that carried the conversion webhook). Remove any stale copy left over
	// from a previous generator run, since chartCRDsSplitGlob does not match it.
	if err := os.Remove(chartCRDsFilePath); err != nil && !os.IsNotExist(err) {
		fmt.Printf("Failed to remove stale %s: %v\n", chartCRDsFilePath, err)
		os.Exit(1)
	}

	for _, splitChartCRDFile := range splitChartCRDFiles {
		if err := writeGeneratedFile(
			splitChartCRDFile.filePath,
			autoGenerationComment,
			wrapInIfEnabled(splitChartCRDFile.content),
		); err != nil {
			fmt.Printf("Failed to write %s: %v\n", splitChartCRDFile.filePath, err)
			os.Exit(1)
		}
	}

	fmt.Println("Successfully finished")
}

func splitChartCRDs(crdContent string, templatesDir string) ([]chartCRDFile, error) {
	documents := splitYAMLDocuments(crdContent)
	splitChartCRDFiles := make([]chartCRDFile, 0, len(documents))

	for _, document := range documents {
		manifest, err := parseCustomResourceDefinitionManifest(document)
		if err != nil {
			return nil, err
		}

		document = ifHelmResourcePolicyKeepAnnotation(document)

		splitChartCRDFileName, err := splitChartCRDFileName(manifest.Metadata.Name)
		if err != nil {
			return nil, err
		}
		splitChartCRDFiles = append(splitChartCRDFiles, chartCRDFile{
			filePath: filepath.Join(templatesDir, splitChartCRDFileName),
			content:  document,
		})
	}

	if len(splitChartCRDFiles) == 0 {
		return nil, fmt.Errorf("no CRDs found to split into %s", templatesDir)
	}

	return splitChartCRDFiles, nil
}

func splitYAMLDocuments(content string) []string {
	lines := strings.Split(content, "\n")
	var documents []string
	currentDocument := make([]string, 0, len(lines))

	appendDocument := func() {
		document := strings.TrimSpace(strings.Join(currentDocument, "\n"))
		if document == "" {
			return
		}
		documents = append(documents, document)
	}

	for _, line := range lines {
		if line == "---" {
			appendDocument()
			currentDocument = currentDocument[:0]
			continue
		}
		currentDocument = append(currentDocument, line)
	}
	appendDocument()

	return documents
}

func parseCustomResourceDefinitionManifest(document string) (customResourceDefinitionManifest, error) {
	var manifest customResourceDefinitionManifest
	decoder := yaml.NewYAMLOrJSONDecoder(strings.NewReader(document), len(document))
	if err := decoder.Decode(&manifest); err != nil {
		return manifest, fmt.Errorf("failed to decode CRD document: %w", err)
	}
	if manifest.Kind != "CustomResourceDefinition" {
		return manifest, fmt.Errorf("unexpected manifest kind %q", manifest.Kind)
	}
	if manifest.Metadata.Name == "" {
		return manifest, fmt.Errorf("decoded CRD document has empty metadata.name")
	}
	if manifest.Spec.Names.Kind == "" {
		return manifest, fmt.Errorf("decoded CRD %q has empty spec.names.kind", manifest.Metadata.Name)
	}
	return manifest, nil
}

func splitChartCRDFileName(crdName string) (string, error) {
	resource, group, found := strings.Cut(crdName, ".")
	if !found {
		return "", fmt.Errorf("invalid CRD name %q", crdName)
	}
	return fmt.Sprintf("ko-crds-%s_%s.yaml", group, resource), nil
}

func removeGeneratedSplitChartCRDFiles(templatesDir string) error {
	files, err := filepath.Glob(filepath.Join(templatesDir, chartCRDsSplitGlob))
	if err != nil {
		return fmt.Errorf("failed to list split CRD files: %w", err)
	}
	for _, file := range files {
		if err := os.Remove(file); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("failed to remove %s: %w", file, err)
		}
	}
	return nil
}

func writeGeneratedFile(filePath string, content ...string) error {
	fmt.Println("Generating", filePath)
	return os.WriteFile(filePath, []byte(strings.Join(content, "")), 0o600)
}

func wrapInIfEnabled(v string) string {
	return fmt.Sprintf("{{- if .Values.enabled }}\n%s\n{{- end }}\n", v)
}

func ifHelmResourcePolicyKeepAnnotation(content string) string {
	const pattern = "metadata:\n  annotations:\n"
	return strings.ReplaceAll(
		content,
		pattern,
		pattern+"{{ if .Values.keep }}\n    helm.sh/resource-policy: keep\n{{ end }}\n",
	)
}
