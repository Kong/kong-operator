// -----------------------------------------------------------------------------
// aiconfigurationv1alpha1 AIGatewayConsumerCredential - Reconciler
// -----------------------------------------------------------------------------

// AIGatewayConsumerCredentialReconciler reports the on-prem configuration status of the
// AIGatewayConsumerCredentials embedded in the consumers' rendered documents.
//
// It is hand-written instead of generated by hack/generators/controllers/aigw, unlike every
// other configuration-entity reconciler of this package: the generated template resolves the
// OnPremAIGateway an entity belongs to from the entity's own aiGatewayRef, for both the
// ChangeNotifier calls and the For predicate. A credential carries no aiGatewayRef — it points
// at an AIGatewayConsumer, and its gateway is only reachable through that consumer — so
// covering it in the template would add per-kind hooks to a template shared by all the other
// kinds, for this one entity.
//
// The reconciler therefore only reports the Programmed condition - writing it, and clearing
// it when the credential's consumer is gone - and never feeds the ChangeNotifier: a
// credential event is already mapped to its parent consumer (see mapCredentialToConsumer),
// and the consumer's own reconciler is what notifies the gateway.
type AIGatewayConsumerCredentialReconciler struct {
	client.Client

	Log          logr.Logger
	StatusClient EntityStatusClient
	StatusQueue  *status.Queue
}

// SetupWithManager sets up the controller with the Manager.
func (r *AIGatewayConsumerCredentialReconciler) SetupWithManager(mgr ctrl.Manager) error {
	blder := ctrl.NewControllerManagedBy(mgr).
		// set the controller name
		Named("aiconfigurationv1alpha1AIGatewayConsumerCredential")
	// if configured, start the status updater controller
	if r.StatusQueue != nil {
		blder.WatchesRawSource(
			source.Channel(
				r.StatusQueue.Subscribe(schema.GroupVersionKind{
					Group:   "aiconfiguration.konghq.com",
					Version: "v1alpha1",
					Kind:    "AIGatewayConsumerCredential",
				}),
				&handler.EnqueueRequestForObject{},
			),
		)
	}
	// No on-prem target predicate is possible here: the parent consumer, not the credential,
	// holds the aiGatewayRef. Resolving the consumer needs a client, and the check is done in
	// Reconcile instead — the events it lets through for Konnect-managed credentials cost one
	// cached Get each and write nothing.
	return blder.
		For(
			&aiconfigurationv1alpha1.AIGatewayConsumerCredential{},
			builder.WithPredicates(GenerationChangedPredicate{}),
		).
		Complete(r)
}

//+kubebuilder:rbac:groups=aiconfiguration.konghq.com,resources=aigatewayconsumercredentials,verbs=get;list;watch
// The status subresource is only written here: the Konnect reconciler holds the same grants.
//+kubebuilder:rbac:groups=aiconfiguration.konghq.com,resources=aigatewayconsumercredentials/status,verbs=update;patch

// Reconcile processes the watched objects.
func (r *AIGatewayConsumerCredentialReconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	obj := new(aiconfigurationv1alpha1.AIGatewayConsumerCredential)
	logger := r.Log.
		WithValues("aiconfigurationv1alpha1AIGatewayConsumerCredential", req.NamespacedName).
		WithValues("namespace", req.Namespace).
		WithValues("name", req.Name).
		V(logging.DebugLevel.Value())
	logger.Info("Reconciling resource")

	if err := r.Get(ctx, req.NamespacedName, obj); err != nil {
		// A deleted credential has no status left to report, and the consumer's re-render
		// is driven by the credential's own watch, not by this reconciler.
		return ctrl.Result{}, client.IgnoreNotFound(err)
	}

	// Credentials of a consumer that does not target an OnPremAIGateway are owned by the
	// Konnect reconciler: writing an on-prem status on one would overwrite its Konnect
	// condition. An unresolvable consumer (absent, or referenced across namespaces) is
	// likewise not ours to report.
	if !credentialOnPremManaged(ctx, r.Client, obj) {
		// A credential whose consumer is gone is rendered by nothing, so the Programmed
		// condition written while it still was claims a rendering that no longer exists:
		// clear it. Only that case is corrected here - the status of a credential with a
		// Konnect-managed consumer is the Konnect reconciler's to write and to clear.
		if credentialOrphaned(ctx, r.Client, obj) {
			return patch.StatusWithoutCondition(ctx, r.Client, obj, string(configurationv1.ConditionProgrammed))
		}
		return ctrl.Result{}, nil
	}

	if r.StatusClient != nil && r.StatusClient.AreKubernetesObjectReportsEnabled() {
		configurationStatus := r.StatusClient.KubernetesObjectConfigurationStatus(obj)
		logger.Info("Updating programmed condition status", "configuration_status", configurationStatus)
		conditions, updateNeeded := ctrlutils.EnsureProgrammedCondition(
			configurationStatus,
			obj.Generation,
			obj.Status.Conditions,
			ctrlutils.WithFailedMessage(r.StatusClient.KubernetesObjectConfigurationStatusMessage(obj)),
		)
		obj.Status.Conditions = conditions
		if updateNeeded {
			if err := r.Status().Update(ctx, obj); err != nil {
				if apierrors.IsConflict(err) {
					return ctrl.Result{
						RequeueAfter: ctrlconsts.RequeueWithoutBackoff,
					}, nil
				}
				return ctrl.Result{}, err
			}

			return ctrl.Result{
				RequeueAfter: ctrlconsts.RequeueWithoutBackoff,
			}, nil
		}

		logger.Info("Status update not needed")
	}

	return ctrl.Result{}, nil
}
