package generator

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
	"text/template"

	"github.com/gobuffalo/flect"
)

const (
	// onPremEventGatewayGroup and onPremEventGatewayKind identify the gateway
	// whose entities GenerateOnPremEventGatewayEntitiesDispatcher lists.
	onPremEventGatewayGroup = "eventgateway.konghq.com"
	onPremEventGatewayKind  = "OnPremEventGateway"

	// OnPremEventGatewayEntitiesFile is the file emitted by
	// GenerateOnPremEventGatewayEntitiesDispatcher, in
	// OnPremEventGatewayEntitiesDir.
	OnPremEventGatewayEntitiesFile = "zz_generated_entities.go"

	// OnPremEventGatewayEntitiesDir is the directory of the OnPremEventGateway
	// controller, relative to the project root.
	OnPremEventGatewayEntitiesDir = "controller/eventgateway/onprem"
)

// onPremGatewayEntity is an entity that can belong to an on-prem gateway.
type onPremGatewayEntity struct {
	Entity   string
	APIAlias string
	Group    string
	Resource string
}

// GenerateOnPremEventGatewayEntitiesDispatcher emits
// controller/eventgateway/onprem/zz_generated_entities.go, listing the
// entities that can belong to an OnPremEventGateway: the entities whose
// gatewayRef accepts it and, transitively, their children. The controller
// watches them, checks their CRDs are installed, gets the RBAC to read them
// and registers the indexes that find them by gateway.
// Call after all per-group generation has finished.
func GenerateOnPremEventGatewayEntitiesDispatcher(infos []*WatchFileInfo) (*GeneratedFile, error) {
	key := func(group, kind string) string { return group + "/" + kind }

	selected := make(map[string]*WatchFileInfo)
	for _, info := range infos {
		for _, gvk := range info.GatewayKinds {
			if gvk.Group == onPremEventGatewayGroup && gvk.Kind == onPremEventGatewayKind {
				selected[key(info.Group, info.Entity)] = info
			}
		}
	}
	if len(selected) == 0 {
		return nil, nil
	}
	for added := true; added; {
		added = false
		for _, info := range infos {
			if _, ok := selected[key(info.Group, info.Entity)]; ok || info.ParentKind == "" {
				continue
			}
			if _, ok := selected[key(info.ParentGroup, info.ParentKind)]; ok {
				selected[key(info.Group, info.Entity)] = info
				added = true
			}
		}
	}

	entities := make([]onPremGatewayEntity, 0, len(selected))
	imports := make(map[string]string)
	groups := make(map[string][]string)
	for _, info := range selected {
		resource := flect.Pluralize(strings.ToLower(info.Entity))
		entities = append(entities, onPremGatewayEntity{
			Entity:   info.Entity,
			APIAlias: info.APIAlias,
			Group:    info.Group,
			Resource: resource,
		})
		imports[info.APIPackagePath] = info.APIAlias
		groups[info.Group] = append(groups[info.Group], resource)
	}
	sort.Slice(entities, func(i, j int) bool { return entities[i].Entity < entities[j].Entity })

	importPaths := make([]string, 0, len(imports))
	for path := range imports {
		importPaths = append(importPaths, path)
	}
	sort.Strings(importPaths)
	importLines := make([]string, 0, len(importPaths))
	for _, path := range importPaths {
		importLines = append(importLines, fmt.Sprintf("%s %q", imports[path], path))
	}

	groupNames := make([]string, 0, len(groups))
	for group := range groups {
		groupNames = append(groupNames, group)
	}
	sort.Strings(groupNames)
	rbacMarkers := make([]string, 0, len(groupNames))
	for _, group := range groupNames {
		resources := groups[group]
		sort.Strings(resources)
		rbacMarkers = append(rbacMarkers, fmt.Sprintf(
			"// +kubebuilder:rbac:groups=%s,resources=%s,verbs=get;list;watch",
			group, strings.Join(resources, ";"),
		))
	}

	tmpl := template.Must(template.New("onprem-eventgateway-entities").Parse(onPremEventGatewayEntitiesTemplate))
	var buf strings.Builder
	if err := tmpl.Execute(&buf, struct {
		Imports     []string
		RBACMarkers []string
		Entities    []onPremGatewayEntity
	}{
		Imports:     importLines,
		RBACMarkers: rbacMarkers,
		Entities:    entities,
	}); err != nil {
		return nil, err
	}

	formatted, err := format.Source([]byte(buf.String()))
	if err != nil {
		return nil, fmt.Errorf("failed to format generated %s: %w", OnPremEventGatewayEntitiesFile, err)
	}

	return &GeneratedFile{
		Name:        OnPremEventGatewayEntitiesFile,
		Content:     string(formatted),
		RelativeDir: OnPremEventGatewayEntitiesDir,
	}, nil
}

