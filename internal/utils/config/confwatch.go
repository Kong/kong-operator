package config

import (
	"fmt"
	"slices"
	"sort"
	"strings"

	corev1 "k8s.io/api/core/v1"
)

// -----------------------------------------------------------------------------
// Utils - Kong configuration file watching
// -----------------------------------------------------------------------------

// confWatchManagedEnvVar describes a Kong setting that the operator renders into
// the watched kong.conf instead of setting it as a KONG_* environment variable.
type confWatchManagedEnvVar struct {
	// name is the KONG_* environment variable name.
	name string
	// resetValue is written to the file when the setting is not configured at
	// all. It is needed because `kong reload -c` merges the file on top of the
	// running configuration: a key that simply disappears from the file keeps
	// its last value instead of reverting to its default. An empty resetValue
	// means the key is omitted when unset.
	resetValue string
}

// confWatchManagedEnvVars is the set of Kong settings the operator moves from
// environment variables into the watched kong.conf when the feature is enabled.
//
// These are exactly the listen-related settings that change when a Gateway
// listener is added, changed or removed. Everything else stays an environment
// variable: an environment variable always wins over the file, so moving a
// setting that never changes buys nothing and only widens the blast radius.
//
// In particular KONG_ADMIN_LISTEN and KONG_STATUS_LISTEN deliberately stay
// environment variables. They are operator-internal, they do not change with
// the Gateway's listeners, and admin_listen is entangled with the cluster
// certificate and the Konnect extension.
var confWatchManagedEnvVars = []confWatchManagedEnvVar{
	{name: "KONG_PROXY_LISTEN"},
	// Kong's default for stream_listen is "off". Without the reset, removing the
	// last stream listener would leave the previous value in place until the Pod
	// restarts.
	{name: "KONG_STREAM_LISTEN", resetValue: "off"},
	{name: "KONG_PORT_MAPS"},
}

// ConfWatchManagedEnvVarNames returns the names of the environment variables the
// operator renders into the watched kong.conf.
func ConfWatchManagedEnvVarNames() []string {
	names := make([]string, 0, len(confWatchManagedEnvVars))
	for _, e := range confWatchManagedEnvVars {
		names = append(names, e.name)
	}
	return names
}

// EnvVarNameToKongConfKey converts a KONG_* environment variable name to the
// kong.conf key it corresponds to, e.g. KONG_PROXY_LISTEN -> proxy_listen.
func EnvVarNameToKongConfKey(name string) string {
	return strings.ToLower(strings.TrimPrefix(name, "KONG_"))
}

// ExtractConfWatchEnvVars splits the given environment variables into the ones
// the operator renders into the watched kong.conf and the ones that stay on the
// container.
//
// An environment variable sourced from elsewhere (ValueFrom) is never moved: its
// value is not known at reconciliation time, so it cannot be rendered into the
// file. It is left on the container, where it keeps working as it does today
// (and keeps winning over the file).
func ExtractConfWatchEnvVars(env []corev1.EnvVar) (managed map[string]string, remaining []corev1.EnvVar) {
	managedNames := ConfWatchManagedEnvVarNames()

	managed = make(map[string]string, len(managedNames))
	remaining = make([]corev1.EnvVar, 0, len(env))

	for _, e := range env {
		if !slices.Contains(managedNames, e.Name) || e.ValueFrom != nil {
			remaining = append(remaining, e)
			continue
		}
		managed[e.Name] = e.Value
	}

	return managed, remaining
}

// RenderKongConf renders the watched kong.conf from the given KONG_* environment
// variable values, keyed by environment variable name.
//
// Every managed key is always written, using its reset value when it is not in
// envValues, because `kong reload -c` merges the file on top of the running
// configuration and never reverts a key that disappears.
//
// The output is deterministic so that an unchanged configuration produces
// byte-identical contents and the in-container watcher does not reload.
func RenderKongConf(envValues map[string]string) string {
	var sb strings.Builder

	sb.WriteString("# Generated by the Kong Operator. Do not edit.\n")
	sb.WriteString("#\n")
	sb.WriteString("# This file is watched by the Kong Gateway container. A change to it triggers\n")
	sb.WriteString("# `kong reload`, which rotates the Nginx workers without replacing the Pod.\n")
	sb.WriteString("#\n")
	sb.WriteString("# A KONG_* environment variable always wins over the keys below, so the\n")
	sb.WriteString("# operator does not set these as environment variables while this file is in\n")
	sb.WriteString("# use.\n")

	keys := make([]string, 0, len(confWatchManagedEnvVars))
	rendered := make(map[string]string, len(confWatchManagedEnvVars))

	for _, e := range confWatchManagedEnvVars {
		value, ok := envValues[e.name]
		if !ok || strings.TrimSpace(value) == "" {
			if e.resetValue == "" {
				continue
			}
			value = e.resetValue
		}
		key := EnvVarNameToKongConfKey(e.name)
		keys = append(keys, key)
		rendered[key] = value
	}

	sort.Strings(keys)
	for _, k := range keys {
		sb.WriteString(fmt.Sprintf("%s = %s\n", k, rendered[k]))
	}

	return sb.String()
}
